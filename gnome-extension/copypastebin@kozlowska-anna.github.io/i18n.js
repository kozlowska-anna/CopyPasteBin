export function languageFromArgs(args) {
    if (!Array.isArray(args) || args.length !== 1)
        return 'en';
    if (args[0] === '--language=pl')
        return 'pl';
    return 'en';
}

export function translate(language, message, values = {}) {
    let rendered = language === 'pl' ? (POLISH.get(message) ?? message) : message;
    for (const [name, value] of Object.entries(values))
        rendered = rendered.replaceAll(`{${name}}`, String(value));
    return rendered;
}
